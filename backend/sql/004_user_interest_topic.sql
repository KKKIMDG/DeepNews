-- Interest topics (BigKinds top-level categories) picked at sign-up or later in the panel.
-- They seed recommendations before any reading history exists (see personalization.ranking.topic_strength).
create table if not exists public.user_interest_topic (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.app_user(id) on delete cascade,
    topic varchar(20) not null,
    created_at timestamptz not null default now(),
    constraint unique_user_topic unique (user_id, topic)
);

create index if not exists idx_user_interest_topic_user_id on public.user_interest_topic (user_id);
