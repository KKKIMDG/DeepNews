create table if not exists public.app_user (
    id bigint generated by default as identity primary key,
    email varchar(320) not null unique,
    password_hash varchar(255) not null,
    ad_filter_threshold numeric(3, 2) not null default 0.80,
    created_at timestamptz not null default now()
);

create table if not exists public.user_session (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.app_user(id) on delete cascade,
    token_hash char(64) not null unique,
    created_at timestamptz not null default now(),
    expires_at timestamptz not null
);

create table if not exists public.user_read_history (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.app_user(id) on delete cascade,
    news_id bigint not null references public.news(id) on delete cascade,
    read_count int4 not null default 1,
    first_read_at timestamptz not null default now(),
    last_read_at timestamptz not null default now(),
    constraint unique_user_news unique (user_id, news_id)
);

create table if not exists public.user_keyword_preference (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.app_user(id) on delete cascade,
    word varchar(255) not null,
    preference varchar(8) not null check (preference in ('include', 'exclude')),
    created_at timestamptz not null default now(),
    constraint unique_user_keyword unique (user_id, word)
);

create index if not exists idx_user_session_user_id on public.user_session(user_id);
create index if not exists idx_user_read_history_user_last_read on public.user_read_history(user_id, last_read_at desc);
create index if not exists idx_user_keyword_preference_user_id on public.user_keyword_preference(user_id);
