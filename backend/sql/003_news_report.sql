-- Reports that a shared analysis does not match the article. Enough distinct reporters drop the
-- analysis so the next browser submission re-analyzes it (see news.service.REANALYSIS_REPORTS).
create table if not exists public.news_report (
    id bigint generated by default as identity primary key,
    news_id bigint not null references public.news(id) on delete cascade,
    user_id bigint not null references public.app_user(id) on delete cascade,
    reason varchar(300) not null default '',
    created_at timestamptz not null default now(),
    constraint unique_news_report unique (news_id, user_id)
);

create index if not exists idx_news_report_news_id on public.news_report (news_id);
